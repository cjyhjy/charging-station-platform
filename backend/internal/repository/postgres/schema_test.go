func readP0Migration(t *testing.T) string {
	t.Helper()
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("resolve test filename")
	}
	migrationPath := filepath.Join(filepath.Dir(filename), "../../../migrations/0001_init.sql")
	contents, err := os.ReadFile(migrationPath)
	if err != nil {
		t.Fatalf("read migration: %v", err)
	}
	return strings.ToLower(string(contents))
}

func tableBlocks(schema string) map[string]string {
	blocks := make(map[string]string)
	parts := strings.Split(schema, "create table if not exists ")
	for _, part := range parts[1:] {
		name := part
		if idx := strings.IndexAny(name, " \t\n("); idx >= 0 {
			name = name[:idx]
		}
		blocks[name] = part
	}
	return blocks
}

// readMigration returns one numbered migration, lower-cased like the P0 helper.
func readMigration(t *testing.T, name string) string {
	t.Helper()
	_, filename, _, ok := runtime.Caller(0)
	if !ok {
		t.Fatal("resolve test filename")
	}
	contents, err := os.ReadFile(filepath.Join(filepath.Dir(filename), "../../../migrations/", name))
	if err != nil {
		t.Fatalf("read migration %s: %v", name, err)
	}
	return strings.ToLower(string(contents))
}

// The BE-I-02 review: the record that keeps one device verdict from being applied twice was an
// idempotency record with a 24-hour window, and an order in STOPPING is still meaningful a day
// later. The structure is therefore the invariant: a command outcome is a permanent fact, so the
// table is keyed by the command id, constrained to the frozen enum, and has no expiry column at all.
func TestChargerCommandOutcomeTableIsDurable(t *testing.T) {
	schema := readMigration(t, "0007_charger_command_outcomes.sql")

	block, ok := tableBlocks(schema)["charger_command_outcomes"]
	if !ok {
		t.Fatal("0007 must define charger_command_outcomes")
	}
	for _, needle := range []string{
		// One command, one verdict: the primary key is the command id itself.
		"command_id text primary key",
		// The database refuses a value the platform must not act on.
		"result text not null check (result in ('completed', 'failed'))",
		"action text not null check (action in ('restart', 'start_charging', 'stop_charging'))",
		"applied boolean not null",
	} {
		if !strings.Contains(block, needle) {
			t.Errorf("charger_command_outcomes must declare %q", needle)
		}
	}
	// Durability is the point: no expiry, no TTL, nothing that would let a duplicate be applied
	// again once a window has passed.
	for _, forbidden := range []string{"expires_at", "expires", "ttl"} {
		if strings.Contains(block, forbidden) {
			t.Errorf("charger_command_outcomes must not expire, found %q", forbidden)
		}
	}
}

