func TestP0MigrationUsesContractIDTypes(t *testing.T) {
	schema := readP0Migration(t)
	blocks := tableBlocks(schema)

	// The frozen OpenAPI contract exposes int64 IDs for these aggregates, so
	// their surrogate keys must be BIGINT identity columns.
	for _, table := range []string{
		"user_accounts",
		"admin_accounts",
		"stations",
		"chargers",
		"charging_orders",
		"order_events",
		"wallet_transactions",
		"operation_logs",
		"outbox_events",
	} {
		block, ok := blocks[table]
		if !ok {
			t.Fatalf("migration does not define %s", table)
		}
		if !strings.Contains(block, "id bigint generated by default as identity primary key") {
			t.Errorf("%s must declare id as bigint identity primary key", table)
		}
	}
	if block, ok := blocks["wallet_accounts"]; !ok || !strings.Contains(block, "user_id bigint primary key") {
		t.Errorf("wallet_accounts must declare user_id as bigint primary key")
	}
	if strings.Contains(schema, "id text primary key") {
		t.Errorf("surrogate primary keys must be bigint identity, not text")
	}

	for _, needle := range []string{
		"station_id bigint not null references stations (id)",
		"user_id bigint not null references user_accounts (id)",
		"charger_id bigint not null references chargers (id)",
		"order_id bigint not null references charging_orders (id)",
		"order_id bigint references charging_orders (id)",
	} {
		if !strings.Contains(schema, needle) {
			t.Errorf("migration missing foreign key requirement %q", needle)
		}
	}
}

func TestP0MigrationMatchesFrozenContract(t *testing.T) {
	schema := readP0Migration(t)
	blocks := tableBlocks(schema)

	stations := blocks["stations"]
	for _, needle := range []string{
		"status text not null default 'open' check (status in ('open', 'closed', 'disabled'))",
	} {
		if !strings.Contains(stations, needle) {
			t.Errorf("stations status must match the frozen StationStatus contract: %q", needle)
		}
	}

	chargers := blocks["chargers"]
	for _, needle := range []string{
		"connector_type text not null default 'ac' check (connector_type in ('ac', 'dc'))",
		"power_watt bigint not null default 0 check (power_watt >= 0)",
		"status text not null default 'idle' check (status in ('idle', 'occupied', 'fault', 'restarting', 'disabled'))",
		"unique (id, station_id)",
	} {
		if !strings.Contains(chargers, needle) {
			t.Errorf("chargers columns must match the frozen Charger contract: %q", needle)
		}
	}

	orders := blocks["charging_orders"]
	for _, needle := range []string{
		"status text not null default 'created' check (status in ('created', 'starting', 'charging', 'stopping', 'completed', 'cancelled', 'expired', 'failed'))",
		"order_no text not null unique",
		// An order's station must be the charger's station.
		"foreign key (charger_id, station_id) references chargers (id, station_id)",
	} {
		if !strings.Contains(orders, needle) {
			t.Errorf("charging_orders columns must match the frozen Order contract: %q", needle)
		}
	}

	outbox := blocks["outbox_events"]
	for _, needle := range []string{
		"event_id text not null unique",
		"trace_id text not null default ''",
		"stream text not null default ''",
	} {
		if !strings.Contains(outbox, needle) {
			t.Errorf("outbox_events must carry the approved OutboxRecord fields: %q", needle)
		}
	}

	for _, needle := range []string{
		// One active order per charger, enforced by the database.
		"create unique index if not exists uq_orders_charger_active",
		"where status in ('created', 'starting', 'charging', 'stopping')",
	} {
		if !strings.Contains(schema, needle) {
			t.Errorf("migration missing concurrency constraint %q", needle)
		}
	}
}

